import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import {resolve} from 'node:path';
import {pool} from './config/db.js';
import auth from './routes/auth.js';
import donations from './routes/donations.js';
import reservations from './routes/reservations.js';
import pickups from './routes/pickups.js';
import organizations from './routes/organizations.js';
import incidents from './routes/incidents.js';
import notifications from './routes/notifications.js';
import impact from './routes/impact.js';
import uploads from './routes/uploads.js';
import users from './routes/users.js';
import schedules from './routes/schedules.js';
if(!process.env.JWT_SECRET||process.env.JWT_SECRET.length<32)throw new Error('Set a secure JWT_SECRET (32+ characters) in .env');
if(!process.env.DATABASE_URL)throw new Error('Set DATABASE_URL in .env');
const app=express();app.disable('x-powered-by');app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
const origins=(process.env.FRONTEND_ORIGINS||'http://localhost:5173').split(',').map(x=>x.trim());
app.use(cors({origin:(origin,cb)=>!origin||origins.includes(origin)?cb(null,true):cb(new Error('CORS origin not allowed'))}));
app.use(express.json({limit:'200kb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:60,standardHeaders:'draft-7',legacyHeaders:false}),auth);
app.use('/api/donations',donations);app.use('/api/reservations',reservations);app.use('/api/pickups',pickups);
app.use('/api/organizations',organizations);app.use('/api/incidents',incidents);app.use('/api/notifications',notifications);
app.use('/api/impact',impact);app.use('/api/uploads',uploads);app.use('/api/users',users);app.use('/api/donor/schedules',schedules);
app.use('/uploads',express.static(resolve(process.env.UPLOAD_DIR||'uploads'),{dotfiles:'deny',index:false}));
app.get('/api/health',async(req,res,next)=>{try{await pool.query('SELECT 1');res.json({ok:true,service:'foodbridge-api'});}catch(e){next(e);}});
app.use((req,res)=>res.status(404).json({error:{code:'NOT_FOUND',message:'Endpoint not found'}}));
app.use((err,req,res,next)=>{
 const status=err.status|| (err.code==='LIMIT_FILE_SIZE'?413:500);
 if(status>=500)console.error(err);
 res.status(status).json({error:{code:status===500?'INTERNAL_ERROR':err.code||'REQUEST_ERROR',message:status===500?'Unexpected server error':err.message,details:err.details||undefined}});
});
app.listen(Number(process.env.PORT||5000),()=>console.log(`FoodBridge API listening on http://localhost:${process.env.PORT||5000}`));
